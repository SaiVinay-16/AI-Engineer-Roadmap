def find_max(lst):
    """Return the maximum element in the list."""
    return max(lst)

def find_min(lst):
    """Return the minimum element in the list."""
    return min(lst)

def sort_list(lst):
    """Return the sorted list."""
    return sorted(lst)

def remove_duplicates(lst):
    """Return the list with duplicates removed."""
    return list(set(lst))