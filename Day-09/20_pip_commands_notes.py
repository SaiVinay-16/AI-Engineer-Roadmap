print("📦 Common pip commands:\n")

print("1. Install a package:")
print("   pip install package_name\n")

print("2. Upgrade a package:")
print("   pip install --upgrade package_name\n")

print("3. Uninstall a package:")
print("   pip uninstall package_name\n")

print("4. List installed packages:")
print("   pip list\n")

print("5. Freeze dependencies (for requirements.txt):")
print("   pip freeze > requirements.txt\n")